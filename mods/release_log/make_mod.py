"""Generates mods/release_log: a small, capped log file of TSMod's own events, for crash reports (user, 2026-11-23).

What it logs (and nothing else; the verbose test trace stays in mods/test_logging):
  - recruit joins and refusals, Lua errors in the join hook   (mods/join_release calls TSLOG in its script environments);
  - shops switched on by the unlock repair                    (mods/unlock_repair calls TSLOG);
  - Smuggle steps and refusals                                (mods/c_hooks' "smuggle..." TSLOG lines are forwarded);
  - the deploy screen's unit placements                       (ChangeSortieUnits, logged before the native runs, so the
                                                               line is on disk even if the placement crashes).

The file: TSMod_log.txt, opened by a relative name, so it lands in the game process's working folder. Which folder that
is (likely TRIANGLE_STRATEGY/Binaries/Win64) is [inferred]: confirm in game before release. Capped at 256 KB: a full
file becomes TSMod_log.old.txt (the previous one is dropped) and a new one starts. Every write is inside pcall; when
io or os is missing, nothing happens.

Each target script runs in its own Lua environment, so every target gets its own copy of the logger.
In the build, list this mod after c_hooks, join_release and unlock_repair, and before test_logging.

  python mods/release_log/make_mod.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
VERSION = "v1"

LOGGER = r'''-- [TSMod] Release log (mods/release_log, generated by make_mod.py): TSMod's own events in TSMod_log.txt (game's
-- working folder), capped at 256 KB (then rotated to TSMod_log.old.txt). Never errors out.
TSMOD_RLOG_FILE = "TSMod_log.txt"
TSMOD_RLOG_OLD = "TSMod_log.old.txt"
TSMOD_RLOG_MAX = 262144
function TSMOD_RLOG(...)
  local n, out = select("#", ...), {}
  for i = 1, n do out[#out + 1] = tostring((select(i, ...))) end
  pcall(function()
    local f = io.open(TSMOD_RLOG_FILE, "a")
    if f == nil then return end
    local size = f:seek("end")
    if type(size) == "number" and size > TSMOD_RLOG_MAX then
      f:close()
      pcall(os.remove, TSMOD_RLOG_OLD)
      local okr, moved = pcall(os.rename, TSMOD_RLOG_FILE, TSMOD_RLOG_OLD)
      f = io.open(TSMOD_RLOG_FILE, (okr and moved) and "a" or "w")
      if f == nil then return end
    end
    local stamp = ""
    pcall(function() stamp = os.date("%Y-%m-%d %H:%M:%S") end)
    f:write(stamp, "  %s %s  ", table.concat(out, " "), "\n")
    f:close()
  end)
end
'''

# Story-side scripts: their TSLOG calls (join_release, unlock_repair) go to the release log. Test builds don't define
# TSLOG in these environments either, so this is the only logger there.
STORY = r'''if TSLOG == nil then
  function TSLOG(...) TSMOD_RLOG(...) end
end
'''

# BattleBase: c_hooks defines TSLOG (the test trace, off in releases). Forward only its Smuggle lines.
BATTLE = r'''local tsmod_rl_tslog = TSLOG
function TSLOG(...)
  local first = tostring((select(1, ...)))
  if string.sub(first, 1, 7) == "smuggle" then TSMOD_RLOG(...) end
  if tsmod_rl_tslog ~= nil then return tsmod_rl_tslog(...) end
end
'''

# BattlePreparation: one line per placement on the deploy screen, written before the native runs.
PREP = r'''local tsmod_rl_env = getfenv(1)
local tsmod_rl_place = tsmod_rl_env.ChangeSortieUnits
if type(tsmod_rl_place) == "function" then
  tsmod_rl_env.ChangeSortieUnits = function(...)
    local a = {...}
    pcall(function()
      local names = {}
      if type(a[3]) == "table" then
        for _, u in ipairs(a[3]) do names[#names + 1] = tostring(u) end
      end
      local okq, q = pcall(GetCurrentQuestInfoId)
      TSMOD_RLOG("deploy", okq and tostring(q) or "?", "at", tostring(a[1]), tostring(a[2]), "units", #names, table.concat(names, " "))
    end)
    return tsmod_rl_place(...)
  end
end
'''

TARGETS = [
    ("progress", "Newera_Handling/Progress/Progress", STORY),
    ("worldmap", "Newera_Handling/WorldMap/WorldMapMain", STORY),
    ("scenarioblock", "Newera_Handling/Scenario/CommonDef/ScenarioBlock", STORY),
    ("battlebase", "Newera_Handling/Battle/BattleBase", BATTLE),
    ("battleprep", "Newera_Handling/Battle/BattlePreparation", PREP),
]

if __name__ == "__main__":
    os.makedirs(os.path.join(HERE, "src"), exist_ok=True)
    la = {}
    for tag, target, extra in TARGETS:
        fn = f"{tag}_append.lua"
        body = LOGGER.replace('"  %s %s  "', f'"  {VERSION} {tag}  "') + extra
        with open(os.path.join(HERE, "src", fn), "w", encoding="utf-8", newline="\n") as f:
            f.write(body)
        la[f"src/{fn}"] = target
    mod = {"name": "TSMod_Release_Log",
           "note": "Release: a small capped log of TSMod's own events (TSMod_log.txt in the game's working folder) for "
                   "crash reports. Generated by make_mod.py (see its docstring). After c_hooks, join_release and "
                   "unlock_repair; before test_logging.",
           "lua_append": la}
    with open(os.path.join(HERE, "mod.json"), "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(mod, indent=1) + "\n")
    print("wrote", len(la), "appends")

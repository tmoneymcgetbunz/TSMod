"""Generate mods/npc_prohibit: grey out a recruit on the deploy screen of every battle where that character is
spawned as an NPC (enemy, guest or ally, or a background figure), as vanilla does with AddProhibitedUnits (e.g. the
Ch.14 river battle prohibits Avlora, `UNIT_MASTER_CH_P016`).

User request 2026-11-22. Without it a recruit can be deployed next to their own NPC self; many scripts spawn the NPC
under the recruit's own unit name (`UNIT_MASTER_CH_N007`...), so the two would also share a name [read].

How: each affected battle script gets an append that wraps AddInitialPosition (every battle's setup calls it, whatever
class defines the setup) and calls AddProhibitedUnits once with that battle's list. Lookup is dynamic, so it doesn't
matter which mod's append defines the setup function. Source of the lists: a scan of every battle script for
SpawnUnit / CreateUnitData of a recruit's unit master (`UNIT_MASTER_CH_<id>` or `_<id>_<n>`), plus the cut battles.

Run: .venv/Scripts/python mods/npc_prohibit/make_mod.py
"""
import glob, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
STORY = os.path.join(ROOT, "decompiled", "Newera_Handling", "Scenario", "Story")
ch = open(os.path.join(ROOT, "docs", "CHARACTERS.md"), encoding="utf-8").read()
RECRUITS = dict((i, n) for n, i in re.findall(r"^\| \[([^\]]+)\]\(#[^)]*\) \| ([A-Z]\d{3}) \|", ch, re.M))
assert len(RECRUITS) == 20, RECRUITS
SPAWN = re.compile(r'(?:SpawnUnit|CreateUnitData)\(\s*"([^"]+)",\s*"UNIT_MASTER_CH_([A-Z]\d{3})(?:_\w+)?",\s*"([^"]+)"')
SKIP = {"ms10_x17/ms10_x17_battle_01"}   # prototype script with no level (never loaded)
# Cut battles whose spawns live in our generated appends (mods/cut_battles/make_lua.py) rather than the vanilla source.
EXTRA = {"ms19_x45/ms19_x45_battle_02_old": {"N206"}, "ms21_x48/ms21_x48_battle_01": {"N207"},
         "ms21_x48/ms21_x48_battle_02": {"N206"}}
# Party characters the cut battles spawn as NPCs. Shipped battles prohibit these themselves (Ch.14 river: Avlora);
# the cut drafts never got the call (user, 2026-11-23: Avlora deployable in the cut river battle).
PARTY = {"P002": "Roland", "P003": "Benedict", "P004": "Frederica", "P011": "Julio", "P016": "Avlora"}
# Only while the cut battle itself runs (its own quest id): four of these levels are also shipped battles (Ch.2 Tourney,
# the three Ch.17 route battles), which stay exactly as vanilla.
EXTRA_PARTY = {"ms02_x02/ms02_x02_battle_02": ("QUEST_INFO_TSMOD_CUT_TOURNEY", {"P011"}),
               "ms14_x29/ms14_x29_battle_02": ("QUEST_INFO_TSMOD_CUT_RIVER", {"P016"}),
               "ms17b_x35/ms17b_x35_battle_01": ("QUEST_INFO_TSMOD_CUT_ROLAND", {"P002"}),
               "ms17f_x37/ms17f_x37_battle_01": ("QUEST_INFO_TSMOD_CUT_BENEDICT", {"P003"}),
               "ms17r_x36/ms17r_x36_battle_01": ("QUEST_INFO_TSMOD_CUT_FREDERICA", {"P004"})}
NAMES = dict(RECRUITS, **PARTY)


def scan():
    out, figures = {}, {}
    for f in glob.glob(os.path.join(STORY, "**", "*.lua"), recursive=True):
        rel = os.path.relpath(f, STORY).replace("\\", "/")[:-4]
        if "/Scene/" in "/" + rel or os.path.basename(rel).startswith("sb_"):
            continue
        main = rel[:-len("_common")] if rel.endswith("_common") else rel
        if main in SKIP or not os.path.exists(os.path.join(STORY, main + ".lua")):
            continue
        t = open(f, encoding="utf-8", errors="ignore").read()
        for name, cid, param in SPAWN.findall(t):
            if cid in RECRUITS:
                out.setdefault(main, set()).add(cid)
                if param == "BATTLE_UNITPARAM_OBJECT_TREASURE_CHEST":
                    figures.setdefault(main, set()).add(cid)
    for k, v in EXTRA.items():
        out.setdefault(k, set()).update(v)
    return out, figures


APPEND = '''-- [TSMod] npc_prohibit (generated by mods/npc_prohibit/make_mod.py): recruits whose characters this battle spawns as
-- NPCs are greyed out on the deploy screen, as vanilla does with AddProhibitedUnits. {names}
local tsmod_np_list = {{{ids}}}
local tsmod_np_done = false
local tsmod_np_add = AddInitialPosition
function AddInitialPosition(...)
  if not tsmod_np_done then
    tsmod_np_done = true
    local ok, err = pcall(AddProhibitedUnits, tsmod_np_list)
    if TSLOG ~= nil then pcall(TSLOG, "npc_prohibit", ok, err, unpack(tsmod_np_list)) end
  end
  return tsmod_np_add(...)
end
'''


APPEND_CUT = '''-- [TSMod] npc_prohibit (generated by mods/npc_prohibit/make_mod.py): party characters this cut battle spawns as NPCs
-- are greyed out on the deploy screen, only while the cut battle runs ({quest}). {names}
local tsmod_np_list = {{{ids}}}
local tsmod_np_done = false
local tsmod_np_add = AddInitialPosition
function AddInitialPosition(...)
  if not tsmod_np_done then
    tsmod_np_done = true
    local okq, q = pcall(GetCurrentQuestInfoId)
    if okq and q == "{quest}" then
      local ok, err = pcall(AddProhibitedUnits, tsmod_np_list)
      if TSLOG ~= nil then pcall(TSLOG, "npc_prohibit", ok, err, unpack(tsmod_np_list)) end
    end
  end
  return tsmod_np_add(...)
end
'''


def main():
    out, figures = scan()
    os.makedirs(os.path.join(HERE, "src"), exist_ok=True)
    lua, report = {}, []
    for main_, (quest, ids) in sorted(EXTRA_PARTY.items()):
        assert main_ not in out, main_        # a battle with both lists would need one combined append
        ids = sorted(ids)
        fn = "src/" + main_.replace("/", "__") + "_append.lua"
        names = ", ".join(NAMES[i] for i in ids)
        txt = APPEND_CUT.format(names=names, quest=quest, ids=", ".join(f'"UNIT_MASTER_CH_{i}"' for i in ids))
        open(os.path.join(HERE, fn), "w", encoding="utf-8", newline="\n").write(txt)
        lua[fn] = "Newera_Handling/Scenario/Story/" + main_
        report.append(f"{main_}: {names} (only in {quest})")
    for main_, ids in sorted(out.items()):
        ids = sorted(ids)
        fn = "src/" + main_.replace("/", "__") + "_append.lua"
        names = ", ".join(NAMES[i] for i in ids)
        txt = APPEND.format(names=names, ids=", ".join(f'"UNIT_MASTER_CH_{i}"' for i in ids))
        open(os.path.join(HERE, fn), "w", encoding="utf-8", newline="\n").write(txt)
        lua[fn] = "Newera_Handling/Scenario/Story/" + main_
        fig = sorted(figures.get(main_, ()))
        report.append(f"{main_}: {names}" + (f" (background figure only: {', '.join(RECRUITS[i] for i in fig)})" if fig else ""))
    mod = {"name": "TSMod_NpcProhibit",
           "note": "Grey out recruits on the deploy screen of battles that spawn their character as an NPC "
                   "(AddProhibitedUnits). Generated by make_mod.py; list in report.txt.",
           "lua_append": lua}
    json.dump(mod, open(os.path.join(HERE, "mod.json"), "w", encoding="utf-8", newline="\n"), indent=1)
    open(os.path.join(HERE, "report.txt"), "w", encoding="utf-8", newline="\n").write("\n".join(report) + "\n")
    print(len(lua), "scripts"); print("\n".join(report))


if __name__ == "__main__":
    main()

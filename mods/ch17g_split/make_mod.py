"""Generate mods/ch17g_split: the Ch.17 Golden-route squad split with the 20 recruits (plan: mods/ch17g_plan.md, option 3).

- Before the split screen sets up, every recruit in the party leaves it (plain LeaveParty: keeps accessories), remembering
  its squad: the one already in its save record (save editor, earlier playthrough) or the default (squads.py).
- Optional figures (TSMOD_17G_FIGURES): each recruit is spawned as a standing figure right of its squad's block; they are
  destroyed just before the game's own DecideOrganizeTeam, so the squad decision never sees them.
- After DecideOrganizeTeam: rejoin each recruit and SetPartyTeam it into its squad (the call the developers' debug start
  uses for all 30).
- _G.TSMOD_17G_ACTIVE tells the join hook (another script environment) not to rejoin recruits while the screen runs.
- Log lines "17g ..." go to the test log in test builds (TSLOG), nowhere in release builds.
Run: .venv/Scripts/python mods/ch17g_split/make_mod.py
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import squads

spots = "{" + ", ".join(f'{k} = {{' + ", ".join(f"{{{x}, {y}}}" for x, y in v) + "}" for k, v in squads.SPOTS.items()) + "}"
LUA = f'''-- [TSMod] Ch.17 Golden-route squad split with the TSMod recruits (mods/ch17g_split, generated by make_mod.py).
-- The split screen shows only the vanilla 30; recruits leave the party for it and rejoin into their squads afterwards.
local TSMOD_17G_FIGURES = true      -- recruits shown as standing figures beside their squads (cosmetic; false = off)
local TSMOD_17G_RECRUITS = {squads.LUA_TABLE}
local TSMOD_17G_SPOTS = {spots}
{squads.LUA_CONST}
local function tsmod_17g_log(...)
  if TSLOG ~= nil then pcall(TSLOG, "17g", ...) end
end
local tsmod_17g_out = {{}}
local tsmod_17g_figs = {{}}

local tsmod_17g_orig_init = OnInitalOrganizeTeam
function OnInitalOrganizeTeam()
  tsmod_17g_out = {{}}
  tsmod_17g_figs = {{}}
  pcall(function() _G.TSMOD_17G_ACTIVE = true end)
  for _, e in ipairs(TSMOD_17G_RECRUITS) do
    local u, key = e[1], e[2]
    if IsPartyIn(u) == true then
      local ok, cur = pcall(GetPartyTeam, u)
      local have = ok and tsmod_squad_key(cur) or nil
      if have ~= nil then key = have end
      if LeaveParty(u) == true then
        table.insert(tsmod_17g_out, {{u, key}})
        tsmod_17g_log("out", u, key, have ~= nil and "kept" or "default")
      else
        tsmod_17g_log("leave refused", u)
      end
    end
  end
  tsmod_17g_orig_init()
  if TSMOD_17G_FIGURES then
    local used = {{B = 0, R = 0, F = 0}}
    for _, e in ipairs(tsmod_17g_out) do
      local u, key = e[1], e[2]
      used[key] = used[key] + 1
      local spot = TSMOD_17G_SPOTS[key][used[key]]
      if spot ~= nil then
        local ok, err = pcall(function()
          SpawnUnit(u, u, "BATTLE_UNITPARAM_CH_" .. string.sub(u, 16) .. "_PARTY", spot[1], spot[2], 1, 0, 0)
        end)
        tsmod_17g_log("figure", u, spot[1], spot[2], ok, err)
        if ok then table.insert(tsmod_17g_figs, u) end
      end
    end
  end
end

local tsmod_17g_orig_decide = DecideOrganizeTeam
function DecideOrganizeTeam(...)
  for _, u in ipairs(tsmod_17g_figs) do
    local ok = pcall(DestroyActor, u)
    tsmod_17g_log("figure removed", u, ok)
  end
  tsmod_17g_figs = {{}}
  local r = {{tsmod_17g_orig_decide(...)}}
  for _, e in ipairs(tsmod_17g_out) do
    local u, key = e[1], e[2]
    if IsPartyIn(u) == true or JoinParty(u) == true then
      SetPartyTeam(u, tsmod_squad_const(key))
      tsmod_17g_log("in", u, key)
    else
      tsmod_17g_log("rejoin refused", u)
    end
  end
  tsmod_17g_out = {{}}
  pcall(function() _G.TSMOD_17G_ACTIVE = nil end)
  return unpack(r)
end
'''

os.makedirs(os.path.join(HERE, "src"), exist_ok=True)
with open(os.path.join(HERE, "src", "organizeteam_append.lua"), "w", encoding="utf-8", newline="\n") as f:
    f.write(LUA)
mod = {"name": "TSMod_Ch17G_Split",
       "note": "Ch.17 Golden-route squad split with the recruits (mods/ch17g_plan.md). Generated by make_mod.py. Ships in the release pak.",
       "lua_append": {"src/organizeteam_append.lua": "Newera_Handling/Battle/BattleOrganizeTeam"}}
with open(os.path.join(HERE, "mod.json"), "w", encoding="utf-8", newline="\n") as f:
    json.dump(mod, f, indent=1)
print("wrote ch17g_split")

"""Generate mods/join_release: the release join hook for all 20 TSMod recruits (replaces the dev join mods
join_sycras_exharme + join_batchA..D, which join everyone at Lv45 for testing).

Decision (user, 2026-11-21, docs/DECISIONS.md "Delivery v1"): all recruits join early, at the party's level.
- When: once Anna (P006) is in the party, i.e. right after the Ch.1 battle (Ch.1 has 5 fixed slots and no deployment
  screen; Test 22 gate). On an existing save that already has her, at the next story scene, loading or world map.
- Level: GetLastMainBattleRecommendLevel(), the level the game itself gives late joiners
  (Scenario/CommonDef/ScenarioBlockJoinParty.lua) [read]. Clamped to 1..50.
- Records: New Game creates them (Test 22 [tested]); NG+ untested; existing saves get them from the save editor
  ("Add TSMod recruits"). A unit without a record is skipped silently (JoinParty returns false) and retried next time.
- Hook points: the same three as the tested clean-room delivery (Test 22 Part A: PASS).
Run: .venv/Scripts/python mods/join_release/make_join.py
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "ch17g_split"))
import squads   # default Golden-route squads (mods/ch17g_plan.md)
UNITS = ["N106", "N204", "N005", "N007", "N009", "N104", "N105", "N004", "N006", "N008", "N102", "N203",
         "N202", "N205", "N207", "M103", "N301", "N101", "N103", "N206"]

BODY = '''-- [TSMod] Release join hook (mods/join_release, generated by make_join.py): the 20 recruits join once Anna is in the
-- party (after the Ch.1 battle), at the level the game gives its own late joiners. During the Golden route's squad
-- chapters (Ch.17-20) a recruit without a squad gets its default one (mods/ch17g_plan.md). Silent; never errors out.
local tsmod_join_units = {%s}
local tsmod_join_squads = %s
%s
local function tsmod_golden_squads_active()
  local ok, on = pcall(function()
    local a = GetSysGlobal(SysGlobal.SCENARIO_ANCHOR)
    return a >= EScenarioAnchorSA_MS17S_X38_HD010 and a <= EScenarioAnchorSA_MS20S_X47_HD010
  end)
  return ok and on == true
end
local tsmod_jr_refused_logged = false
local function tsmod_join_release()
  local ok, err = pcall(function()
    if _G ~= nil and rawget(_G, "TSMOD_17G_ACTIVE") then return end     -- the split screen is running
    if IsPartyIn("UNIT_MASTER_CH_P006") ~= true then return end
    local lv = nil
    local refused = {}
    for _, u in ipairs(tsmod_join_units) do
      if IsPartyIn(u) ~= true then
        if JoinParty(u) == true then
          if lv == nil then
            local okl, rec = pcall(GetLastMainBattleRecommendLevel)
            lv = (okl and type(rec) == "number") and rec or 1
            if lv < 1 then lv = 1 elseif lv > 50 then lv = 50 end
          end
          LevelUpToTargetLevel(u, lv)
          if TSLOG ~= nil then pcall(TSLOG, "join", u, "lv", lv) end
        else
          refused[#refused + 1] = u
        end
      end
    end
    if #refused > 0 and not tsmod_jr_refused_logged and TSLOG ~= nil then
      tsmod_jr_refused_logged = true    -- once per level load: a save without the recruits' records refuses every time
      pcall(TSLOG, "join refused (no unit record in this save)", table.concat(refused, " "))
    end
    if tsmod_golden_squads_active() then
      for _, e in ipairs(tsmod_join_squads) do
        if IsPartyIn(e[1]) == true and tsmod_squad_key(GetPartyTeam(e[1])) == nil then
          SetPartyTeam(e[1], tsmod_squad_const(e[2]))
        end
      end
    end
  end)
  if not ok and TSLOG ~= nil then pcall(TSLOG, "join_release: Lua error", err) end
end
'''
UNITS_LUA = ", ".join(f'"UNIT_MASTER_CH_{u}"' for u in UNITS)

FILES = {
    "progress_append.lua": ("Newera_Handling/Progress/Progress", '''local tsmod_jr_orig_loading = Call_LoadingEvent
function Call_LoadingEvent()
  tsmod_join_release()
  tsmod_jr_orig_loading()
end
local tsmod_jr_orig_resume_wm = OnResumeWorldMap
function OnResumeWorldMap()
  tsmod_join_release()
  tsmod_jr_orig_resume_wm()
end
'''),
    "worldmap_append.lua": ("Newera_Handling/WorldMap/WorldMapMain", '''local tsmod_jr_orig_postinit = ClassWorldMapImplementation.OnPostInitialize_Implementation
function ClassWorldMapImplementation:OnPostInitialize_Implementation()
  tsmod_join_release()
  tsmod_jr_orig_postinit(self)
end
'''),
    "scenarioblock_append.lua": ("Newera_Handling/Scenario/CommonDef/ScenarioBlock", '''local tsmod_jr_orig_sb_thread = CreateScenarioBlockThread
function CreateScenarioBlockThread()
  tsmod_join_release()
  tsmod_jr_orig_sb_thread()
end
'''),
}

os.makedirs(os.path.join(HERE, "src"), exist_ok=True)
lua = {}
for fn, (target, hook) in FILES.items():
    with open(os.path.join(HERE, "src", fn), "w", encoding="utf-8", newline="\n") as f:
        f.write(BODY % (UNITS_LUA, squads.LUA_TABLE, squads.LUA_CONST) + hook)
    lua["src/" + fn] = target
mod = {"name": "TSMod_Join_Release",
       "note": "Release delivery: all 20 recruits join after the Ch.1 battle at the game's late-join level. Replaces the dev join mods. Generated by make_join.py.",
       "lua_append": lua}
with open(os.path.join(HERE, "mod.json"), "w", encoding="utf-8", newline="\n") as f:
    json.dump(mod, f, indent=1)
print("wrote", len(FILES), "appends,", len(UNITS), "units")

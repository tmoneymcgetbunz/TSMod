"""Generate docs/CHARACTERS.md, the running character sheet, from the specs and a built pak's staged tables.

    python tools/char_sheet.py mods/_combined/<build>      # the out-dir of the latest combined build

Generated per recruit: classes, learn table, weapons and rank-up materials, tree, weapon skill, Lv50 Elite stats,
and the vanilla-kit check (tools/kit_gaps.py). Names, TP, range and stats are read from the built tables, so the
sheet shows what the pak actually contains. Hand-written design notes live between
`<!-- notes:<id> -->` and `<!-- /notes -->` and are kept when the sheet is regenerated.
Rerun after every build (docs/WORKING_METHOD.md, end of pass).
"""
import json, os, re, sys, datetime
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dtparse as D, kit_gaps, npc_audit

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'docs', 'CHARACTERS.md')
V = lambda v: v['v'] if isinstance(v, dict) else v


def staged(out_dir):
    base = os.path.join(out_dir, 'stage', 'TRIANGLE_STRATEGY', 'Content', 'Newera', 'Data', 'DataTables')
    t = {}
    for n in ('GOP_Battle_Ability', 'GOP_Battle_AttackParam', 'GOP_Battle_UnitGrowth', 'GOP_Battle_Weapon', 'GOP_Battle_Job',
              'GOP_Battle_WeaponAbilityTree', 'GOP_Battle_WeaponAbilityMaterial', 'Text/en/GOP_Text_Ability',
              'Text/en/GOP_Text_Weapon', 'Text/en/GOP_Text_Job'):
        rows = D.parse(os.path.join(base, *n.split('/')) + '.uasset')[1]
        t[n.split('/')[-1]] = {k: {f: V(v) for f, v in r.items()} for k, r in rows.items()}
    return t


def main(out_dir):
    t = staged(out_dir); G = kit_gaps.load()
    common = npc_audit.table('Text/en/GOP_Text_Common'); items = npc_audit.table('Text/en/GOP_Text_Item')
    ta, tw, tj = t['GOP_Text_Ability'], t['GOP_Text_Weapon'], t['GOP_Text_Job']
    ab, ap = t['GOP_Battle_Ability'], t['GOP_Battle_AttackParam']
    txt = lambda tab, k: (tab.get(k, {}).get('Text') or '').replace('\n', ' ')
    nm = lambda a: txt(ta, ab[a]['AbilityName']) if a in ab else a
    def info(a):
        r = ab.get(a); x = ap.get(r['AttackParam']) if r else None
        if not x: return ''
        rng = f"{x['iMinTargetRange']}-{x['iMaxTargetRange']}"
        area = x['eEffectableRangeType'].split('::')[1].lower()
        return f"{x['fUseTP']:g} TP, range {rng}, {area}" + (f" {x['fEffectiveRangeLevel']:g}" if x['fEffectiveRangeLevel'] else '')
    old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
    notes = dict(re.findall(r'<!-- notes:(\w+) -->\n(.*?)<!-- /notes -->', old, re.S))
    L = ['# Character sheet', '',
         f'> Generated by `tools/char_sheet.py` from `{os.path.relpath(out_dir, ROOT).replace(os.sep, "/")}` on '
         f'{datetime.date.today()}. Edit only the **Design notes** blocks; everything else is regenerated.',
         '> Design notes per character are kept by hand; everything else is generated from the build.', '']
    specs = list(kit_gaps.specs())
    L += ['| Recruit | Id | Classes | Weapon | Weapon skill | Lv50 Elite HP / SPD |', '|---|---|---|---|---|---|']
    rows = []
    for s in specs:
        P = s['id'] + 'P'; name = common[f"TEXT_COMMON_CH_NAME_{s['id']}"]['Text']
        jobs = [f'BATTLE_JOB_CH_{P}_{i}' for i in (1, 2, 3)]
        cls = ' → '.join(txt(tj, t['GOP_Battle_Job'][j]['JobName']) for j in jobs)
        w3 = t['GOP_Battle_Weapon'][f'BATTLE_WEAPON_RANK3_{P}']; ws = w3['Ability']
        g = t['GOP_Battle_UnitGrowth'][f'BATTLE_UNITGROWTH_CH_{P}_R3_50']
        rows.append((name, s, P, jobs, ws, g))
        L.append(f"| [{name}](#{name.lower()}) | {s['id']} | {cls} | {txt(tw, w3['WeaponName'])} | "
                 f"{nm(ws) if ws != 'None' else '—'} | {g['fMaxHitPoint']:g} / {g['fUnitSpeed']:g} |")
    passive = lambda a: str(ab.get(a, {}).get('eAbilityCategory', '')).endswith('SUPPORT')
    def vt(n):        # the build's table when staged (recruit copies), else the vanilla dump
        f = os.path.join(out_dir, 'stage', 'TRIANGLE_STRATEGY', 'Content', 'Newera', 'Data', 'DataTables', n + '.uasset')
        if os.path.exists(f):
            return {k: {x: V(v) for x, v in r.items()} for k, r in D.parse(f)[1].items()}
        try:
            j = json.load(open(os.path.join(ROOT, 'data', 'tables', n + '.json'), encoding='utf-8')); return j.get('rows', j)
        except (OSError, ValueError):
            return {}
    sea, se, bfa, bf = vt('GOP_Battle_StatusEffectAtk'), vt('GOP_Battle_StatusEffect'), vt('GOP_Battle_BuffEffectAtk'), vt('GOP_Battle_BuffEffect')
    def turns(a):
        """The numbers the game puts into %_STATUS_EFFECT_TURN_% / %_BUFF_EFFECT_TURN_% (first effect's duration)."""
        x = ap.get(ab.get(a, {}).get('AttackParam'), {}); out = {}
        s1 = sea.get(x.get('StatusEffectId'), {}).get('StatusEffect1')
        if s1 in se: out['%_STATUS_EFFECT_TURN_%'] = str(se[s1].get('iDurationTurn'))
        b1 = bfa.get(x.get('BuffEffectId'), {}).get('BuffEffect1')
        if b1 in bf: out['%_BUFF_EFFECT_TURN_%'] = str(bf[b1].get('iDurationTurn'))
        if x: out['%_ATTACK_RANGE_MAX_%'] = str(x.get('iMaxTargetRange'))
        return out
    def help_(a):
        if a not in ab: return ''
        h = txt(ta, ab[a]['AbilityHelp']).replace('[Passive Skill] ', '').strip()
        for k, v in turns(a).items(): h = h.replace(k, v)
        h = h.replace('%_GOLDNUM_%', 'gold (the amount shows in game)')   # computed by the exe, not in the tables
        return h
    def cell(x): return str(x).replace('|', '/').replace('\r', ' ').replace('  ', ' ')
    def tp_range(a):
        r = ab.get(a); x = ap.get(r['AttackParam']) if r else None
        if passive(a) or not x: return '—', '—'
        area = x['eEffectableRangeType'].split('::')[1].lower()
        size = f" {x['fEffectiveRangeLevel']:g}" if x['fEffectiveRangeLevel'] else ''
        rng = 'self' if x['iMaxTargetRange'] == 0 else f"{x['iMinTargetRange']}-{x['iMaxTargetRange']}"
        return f"{x['fUseTP']:g}", f"{rng}, {area}{size}"
    item_name = lambda i: (common.get('TEXT_COMMON_ITEM_NAME_' + i[5:].replace('CLASSMEDAL', 'MEDAL'), {}).get('Text')
                           or items.get('TEXT_ITEM_NAME_MATERIAL_' + i[21:], {}).get('Text') or i)
    for name, s, P, jobs, ws, g in rows:
        cid = s['id']
        full = common.get(f'TEXT_COMMON_CH_FULLNAME_{cid}', {}).get('Text', name)
        L += ['', f'## {name}', '', f"**{full}** · `{cid}` · {s['job_type'].split('::')[1].lower()}, "
              f"{s['weapon']['icon'].split('::')[1].lower()} · template `{s.get('param_template', '')}`", '']
        prof = txt(tj, t['GOP_Battle_Job'][jobs[0]]['JobHelp'])
        if prof: L += [f'> {prof}', '']
        L += ['**Lv50 Elite stats:** ' + ', '.join(f'{k} {g[f]:g}' for k, f in (('HP', 'fMaxHitPoint'), ('STR', 'fStrength'),
              ('MAG', 'fIntelligence'), ('DEF', 'fDefence'), ('MDF', 'fMagicDefence'), ('SPD', 'fUnitSpeed'), ('TP', 'fMaxTacticalPoint'))) + f", MOV {g['fMoveForce'] / 100:g}", '']
        L += ['**Classes:** ' + ' → '.join(
            txt(tj, t['GOP_Battle_Job'][j]['JobName']) + ('' if i == 0 else
            f" (Lv{t['GOP_Battle_Job'][j]['iNecessaryUnitLevel']}, {item_name(t['GOP_Battle_Job'][j]['NecessaryItem'])})")
            for i, j in enumerate(jobs)), '']
        L += ['| Lv | Class | Ability | Kind | TP | Range, area | Description |', '|---|---|---|---|---|---|---|']
        for j in jobs:
            r = t['GOP_Battle_Job'][j]
            for i in range(1, 11):
                a = r.get(f'LearnableAbility{i}', 'None')
                if a and a != 'None':
                    tp, rg = tp_range(a)
                    L.append(f"| {r[f'iLearnableLevel{i}']} | {txt(tj, r['JobName'])} | {nm(a)} | "
                             f"{'passive' if passive(a) else 'command'} | {tp} | {rg} | {cell(help_(a))} |")
        L += ['', '| Weapon | Unlock | Tree node | Cost | Description |', '|---|---|---|---|---|']
        for i, wid in enumerate((f'BATTLE_WEAPON_{P}', f'BATTLE_WEAPON_RANK2_{P}', f'BATTLE_WEAPON_RANK3_{P}')):
            w = t['GOP_Battle_Weapon'][wid]; tr = t['GOP_Battle_WeaponAbilityTree'][w['WeaponAbilityTree']]
            m = t['GOP_Battle_WeaponAbilityMaterial'].get(w.get('WeaponAbilityMaterial'), {})
            if i == 0: unlock = 'starting weapon'
            else:                                   # a row's RankUp* fields are the cost of reaching that rank
                mat = w.get('RankUpMaterial1', 'None')
                unlock = f"rank up: {w.get('iRankUpMoney', 0)} gold" + ('' if mat in (None, 'None') else
                         f" + {w.get('iRankUpMatrialNum1', 1)}× {item_name(mat)}")
            first = True
            for k in range(1, 6):
                a = tr.get(f'AbilityId{k}', 'None')
                if a in (None, 'None'): continue
                cost = [f"{m.get(f'iMoney_{k}', 0)} gold"] + [f"{m[f'iMaterialNum{q}_{k}']}× {item_name(m[f'MaterialId{q}_{k}'])}"
                        for q in (1, 2) if m.get(f'MaterialId{q}_{k}') not in (None, 'None')]
                L.append(f"| {txt(tw, w['WeaponName']) if first else ''} | {unlock if first else ''} | "
                         f"{nm(a)}{' (weapon skill)' if a == ws else ''} | {', '.join(cost)} | {cell(help_(a))} |")
                first = False
        if ws != 'None':
            tp, rg = tp_range(ws)
            L += ['', f"**Weapon skill:** {nm(ws)} ({tp} TP, range {rg}): {help_(ws)}"]
        L += ['', '**Vanilla kit check** (`tools/kit_gaps.py`):', '']
        for a, st, where in kit_gaps.gaps(cid, s, G):
            L.append(f"- {nm(a) if a in ab else a} `{a[15:]}`: {st}")
        L += ['', '**Design notes:**', f'<!-- notes:{cid} -->', notes.get(cid, '_(none yet)_').strip(), '<!-- /notes -->']
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(L).rstrip() + '\n')
    print('wrote', OUT, len(rows), 'recruits')
    public_pages(rows, dict(t=t, txt=txt, nm=nm, tj=tj, tw=tw, common=common, passive=passive, help_=help_,
                            cell=cell, tp_range=tp_range, item_name=item_name, G=G))


PUB = os.path.join(ROOT, 'characters')


def public_pages(rows, c):
    """characters/<Name>.md + characters/README.md: the player-facing sheets (no ids, templates or design notes)."""
    t, txt, nm, tj, tw, cell = c['t'], c['txt'], c['nm'], c['tj'], c['tw'], c['cell']
    J = t['GOP_Battle_Job']
    os.makedirs(PUB, exist_ok=True)
    idx = ['# TSMod recruits', '',
           "Twenty named characters from Triangle Strategy who join your army with TSMod. Each page lists the character's",
           'classes, every move they learn, their weapon line with its upgrade tree, and their stats.', '',
           "Moves marked ★ come from the character's own kit in the base game (as an enemy or guest); the rest are new.", '',
           '| Character | Classes | Weapon skill |', '|---|---|---|']
    for name, s, P, jobs, ws, g in rows:
        cid = s['id']
        full = c['common'].get(f'TEXT_COMMON_CH_FULLNAME_{cid}', {}).get('Text', name)
        orig = {nm(a) for a, st, where in kit_gaps.gaps(cid, s, c['G'])}
        star = lambda a: nm(a) + (' ★' if nm(a) in orig else '')
        cls = [txt(tj, J[j]['JobName']) for j in jobs]
        fn = name.replace(' ', '_') + '.md'
        idx.append(f"| [{name}]({fn}) | {' → '.join(cls)} | {nm(ws) if ws != 'None' else '—'} |")
        L = [f'# {full}', '', '[All recruits](README.md)', '']
        prof = txt(tj, J[jobs[0]]['JobHelp'])
        if prof: L += [f'> {prof}', '']
        L += ['**Classes:** ' + ' → '.join(
              cls[i] + ('' if i == 0 else f" (level {J[j]['iNecessaryUnitLevel']}, {c['item_name'](J[j]['NecessaryItem'])})")
              for i, j in enumerate(jobs)), '']
        if ws != 'None':
            tp, rg = c['tp_range'](ws)
            L += ['## Weapon skill', '', f"**{star(ws)}** ({tp} TP, range {rg}): {c['help_'](ws)}", '',
                  "Bought as the last node of the rank-3 weapon's upgrade tree.", '']
        L += ['## Moves', '', '| Level | Class | Move | Type | TP | Range, area | Effect |', '|---|---|---|---|---|---|---|']
        for j in jobs:
            r = J[j]
            for i in range(1, 11):
                a = r.get(f'LearnableAbility{i}', 'None')
                if a and a != 'None':
                    tp, rg = c['tp_range'](a)
                    L.append(f"| {r[f'iLearnableLevel{i}']} | {txt(tj, r['JobName'])} | {star(a)} | "
                             f"{'passive' if c['passive'](a) else 'command'} | {tp} | {rg} | {cell(c['help_'](a))} |")
        L += ['', '## Weapon and upgrade tree', '',
              '| Weapon | How to get it | Tree node | Cost | Effect |', '|---|---|---|---|---|']
        for i, wid in enumerate((f'BATTLE_WEAPON_{P}', f'BATTLE_WEAPON_RANK2_{P}', f'BATTLE_WEAPON_RANK3_{P}')):
            w = t['GOP_Battle_Weapon'][wid]; tr = t['GOP_Battle_WeaponAbilityTree'][w['WeaponAbilityTree']]
            m = t['GOP_Battle_WeaponAbilityMaterial'].get(w.get('WeaponAbilityMaterial'), {})
            if i == 0: unlock = 'starting weapon'
            else:
                mat = w.get('RankUpMaterial1', 'None')
                unlock = f"rank up: {w.get('iRankUpMoney', 0)} gold" + ('' if mat in (None, 'None') else
                         f" + {w.get('iRankUpMatrialNum1', 1)}× {c['item_name'](mat)}")
            first = True
            for k in range(1, 6):
                a = tr.get(f'AbilityId{k}', 'None')
                if a in (None, 'None'): continue
                L.append(f"| {txt(tw, w['WeaponName']) if first else ''} | {unlock if first else ''} | "
                         f"{star(a)}{' (weapon skill)' if a == ws else ''} | {m.get(f'iMoney_{k}', 0)} gold | "
                         f"{cell(c['help_'](a))} |")
                first = False
        L += ['', 'On the rank-2 weapon, the third and fourth nodes are either/or, as in the base game.', '',
              '## Stats at level 50 (third class)', '',
              '| HP | Strength | Magic | Defense | Magic defense | Speed | TP | Move |', '|---|---|---|---|---|---|---|---|',
              '| ' + ' | '.join(f'{g[f]:g}' for f in ('fMaxHitPoint', 'fStrength', 'fIntelligence', 'fDefence',
              'fMagicDefence', 'fUnitSpeed', 'fMaxTacticalPoint')) + f" | {g['fMoveForce'] / 100:g} |"]
        open(os.path.join(PUB, fn), 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
    idx += ['', "Generated from the release build by `tools/char_sheet.py`; names and effects are the game's own text."]
    open(os.path.join(PUB, 'README.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(idx) + '\n')
    print('wrote', PUB, len(rows), 'pages')


if __name__ == '__main__':
    main(os.path.abspath(sys.argv[1]))
